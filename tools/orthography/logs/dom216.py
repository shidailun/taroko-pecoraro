# his L-initial heads: the reflexes the lgluq refusal rests on
L_HEADS = {"lbagan": "rbagan", "lb'nao": "rbnaw", "lb'lak": "lblak"}


def read_map():
    t = io.open(os.path.join(SITE, "modern_map.js"), encoding="utf-8").read()
    a = t.index("window.MODERN_MAP = {")
    return dict(re.findall(r'^"(.+?)":"(.+?)",?$',
                           t[a:t.index("\n};", a) + 2], re.M))


def read_ver():
    t = io.open(os.path.join(SITE, "verified.js"), encoding="utf-8").read()
    return dict((k, int(n))
                for k, n in re.findall(r'^  "(.+?)": (\d+),?$', t, re.M))


def main():
    fails = []
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page()
        pg.goto("http://127.0.0.1:8765/")
        pg.evaluate("localStorage.setItem('taroko_pecoraro_spelling_v1','modern')")
        pg.goto(URL)
        pg.wait_for_timeout(WAIT)
        r = pg.evaluate(JS)
        b.close()

    print("rows with spans: %d   all-dark: %d   %.4f%%"
          % (r["tot"], r["ok"], 100.0 * r["ok"] / DENOM))
    if r["tot"] != DENOM:
        fails.append("denominator moved: %d rows carry spans, expected %d"
                     % (r["tot"], DENOM))
    if r["ok"] < FLOOR:
        fails.append("deliverable pairs FELL to %d, floor is %d"
                     % (r["ok"], FLOOR))

    M, V = read_map(), read_ver()

    # 1 — the tnoxoi ruling and the family that carried it
    if M.get("tnoxoi") != "tnuhuy":
        fails.append("map tnoxoi -> %s. Batch 216 retired a tier-M identity pin: "
                     "his sentence is past tense, <n> is the perfective infix, "
                     "and every other slot on the TOXOI card is already ruled."
                     % M.get("tnoxoi"))
    if V.get("tnuhuy") != 2:
        fails.append("tnuhuy is verified %s, batch 216 built it to code 2 "
                     "(regularly inflected off tuhuy)" % V.get("tnuhuy"))
    for k, want in (("toxoi", "tuhuy"), ("ptoxoi", "ptuhuy"),
                    ("tgoxoi", "tghuy"), ("ttgoxoi", "ttguhuy"),
                    ("stgoxoi", "stghuy"), ("txeyan", "thiyan")):
        if M.get(k) != want:
            fails.append("TOXOI family drifted: %s -> %s, expected %s. The "
                         "ruling on tnuhuy rests on this card being ruled."
                         % (k, M.get(k), want))
    if V.get("tuhuy") != 1:
        fails.append("tuhuy is verified %s, expected 1 -- the root the ruling "
                     "inflects off" % V.get("tuhuy"))

    # 2 — the row it cleared
    trows = [h for h in r["hits"] if re.search(r"(?<![a-z])tnuhuy(?![a-z])",
                                               h["t"], re.I)]
    print("rows carrying tnuhuy: %d (floor 1)" % len(trows))
    if not trows:
        fails.append("no rendered row carries tnuhuy; the ruling cleared the "
                     "K'LAP row `Tnoxoi ko munan s'xiga`")
    for h in trows:
        if h["bad"]:
            fails.append("the tnuhuy row is not all dark: %r %s"
                         % (h["t"][:44], h["bad"][:3]))

    # 3 — the pgago freeze, recorded unfixed
    if M.get("pgago") != "pgagu":
        fails.append("map pgago -> %s. Batch 216 RECORDED this as an unfixed "
                     "homograph freeze (pgagu is 笛子, his card is 斑鳩) and "
                     "followed batch 214's remedy of writing it down. If it has "
                     "been fixed, the ledger must name the batch that did it."
                     % M.get("pgago"))

    # 4 + 6 — every refusal still pale, read off the DOM and not off REFUSED.
    # Keys are RENDERED forms; a key that matches nothing passes vacuously
    # (batch 215's slangan/mslangan bug), so absence is itself a failure.
    seen, unv = r["seen"], r["unv"]
    for word, why in sorted(REFUSED.items()):
        if word not in seen:
            fails.append("%s no longer renders anywhere on the page. It was "
                         "refused because %s -- if the transcription or the "
                         "map changed, the refusal needs re-arguing, not "
                         "deleting." % (word, why))
        elif word not in unv:
            fails.append("%s renders %d time(s) and NONE is pale. It was "
                         "refused because %s" % (word, seen[word], why))

    # 5 — the L-initial reflexes
    for k, want in sorted(L_HEADS.items()):
        if M.get(k) != want:
            fails.append("L-head reflex drifted: %s -> %s, expected %s. The "
                         "lgluq refusal rests on his L surfacing as r or l, "
                         "never as zero." % (k, M.get(k), want))

    # 7 — green
    print("green spans: %d %s" % (r["green"], sorted(r["greens"])))
    if r["green"] != GREEN:
        fails.append("green moved to %d spans, batch 216 measured %d (%s). "
                     "Green means no map entry fired; a rise is a generator "
                     "regression, a fall wants a ledger row."
                     % (r["green"], GREEN, sorted(r["greens"])))

    print("\n%d assertions failed" % len(fails))
    for f in fails:
        print("  FAIL", f)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
